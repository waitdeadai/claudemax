// scripts/soc-denamespace.mjs  (Node, ES module — repo is "type":"module")
// Post-fetch reconciliation for the vendored searchoclock plugin.
//
// searchoclock's injected protocol + command dispatch the researcher/validator by their
// PLUGIN-NAMESPACED names (`searchoclock:searchoclock-researcher` /
// `searchoclock:searchoclock-validator`). Those names resolve ONLY when searchoclock is
// installed via `/plugin install`. claudemax VENDORS it instead (gitignored vendor/, like
// llm-dark-patterns), so under vendoring the namespaced dispatch resolves to nothing and the
// double-validation gate silently never runs.
//
// This step rewrites the vendored hook in place to emit BARE agent names, and refreshes the
// committed first-party agents + command from upstream (de-namespaced) so the bare
// `searchoclock-researcher` / `searchoclock-validator` resolve as project-level agents under
// .claude/agents/. Deterministic + re-runnable: it operates on the freshly-cloned upstream
// each time, so the vendored file never drifts from hand edits.
import { readFileSync, writeFileSync, existsSync, mkdirSync } from "node:fs";

const SOC = "vendor/searchoclock";
if (!existsSync(`${SOC}/searchoclock.sh`)) {
  console.warn("  hint: searchoclock not vendored — run: pnpm searchoclock:sync");
  process.exit(0);
}

const denamespace = (s) =>
  s.replaceAll("searchoclock:searchoclock-researcher", "searchoclock-researcher")
   .replaceAll("searchoclock:searchoclock-validator",  "searchoclock-validator");

// Apache-2.0 §4 attribution + "don't hand-edit" notice, injected after the YAML
// frontmatter so these committed copies stay traceable to upstream across re-syncs.
const PROVENANCE =
  "<!-- Vendored from waitdeadai/searchoclock (Apache-2.0), de-namespaced for first-party use. " +
  "Generated by scripts/soc-denamespace.mjs on `pnpm searchoclock:sync` — do not hand-edit. -->";
const withProvenance = (s) => {
  if (s.includes("waitdeadai/searchoclock (Apache-2.0)")) return s;
  const fm = s.match(/^---\n[\s\S]*?\n---\n/);
  return fm ? s.slice(0, fm[0].length) + PROVENANCE + "\n" + s.slice(fm[0].length)
            : PROVENANCE + "\n" + s;
};

// 1) rewrite the vendored hook in place (injected protocol dispatches bare names)
writeFileSync(`${SOC}/searchoclock.sh`, denamespace(readFileSync(`${SOC}/searchoclock.sh`, "utf8")));

// 2) refresh the committed first-party agents + command from upstream, de-namespaced + attributed
mkdirSync(".claude/commands", { recursive: true });
mkdirSync(".claude/agents", { recursive: true });
for (const [src, dst] of [
  [`${SOC}/agents/searchoclock-researcher.md`, ".claude/agents/searchoclock-researcher.md"],
  [`${SOC}/agents/searchoclock-validator.md`,  ".claude/agents/searchoclock-validator.md"],
]) writeFileSync(dst, withProvenance(denamespace(readFileSync(src, "utf8"))));
writeFileSync(".claude/commands/searchoclock.md", withProvenance(denamespace(readFileSync(`${SOC}/commands/searchoclock.md`, "utf8"))));

console.log("  ok    searchoclock de-namespaced (hook + agents + command)");
